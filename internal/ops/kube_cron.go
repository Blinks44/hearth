// PlanKubeCronSuspend previews changing only the CronJob schedule switch.
func PlanKubeCronSuspend(ctx context.Context, r run.Runner, env sysenv.Env, ref KubeResource, suspend bool) (Plan, error) {
	if ref.Kind != "CronJob" || ref.path() == "" {
		return Plan{}, errors.New(locales.KubeResourceTarget())
	}
	change, err := previewKubeToggle(ctx, r, env, ref, "cronjob.batch", "suspend", suspend)
	if err != nil {
		return Plan{}, err
	}
	change.Diff = Diff(fmt.Sprintf("spec.suspend: %t", !suspend), fmt.Sprintf("spec.suspend: %t", suspend))
	title, why, action := locales.KubeCronResumeTitle(ref.Name), locales.KubeCronResumePreview(), locales.KubeCronResumeAction()
	if suspend {
		title, why, action = locales.KubeCronPauseTitle(ref.Name), locales.KubeCronPausePreview(), locales.KubeCronPauseAction()
	}
	return Plan{
		Title: title, Why: why, Action: action, Env: slices.Clone(env),
		Steps: []Step{{Kube: change, Argv: append([]string{ref.Kubectl, "--context=" + ref.Context}, change.command()...)}},
	}, nil
}

// PlanKubeCronRun freezes the Job generated by kubectl so confirmation
// cannot run a different template if the CronJob changes.
func PlanKubeCronRun(ctx context.Context, r run.Runner, env sysenv.Env, ref KubeResource) (Plan, error) {
	if ref.Kind != "CronJob" || ref.path() == "" {
		return Plan{}, errors.New(locales.KubeResourceTarget())
	}
	k, hash, closeConfig, err := (resourceClient{cli: ref.Kubectl, context: ref.Context, env: env, runner: r}).pin(ctx, [32]byte{})
	if err != nil {
		return Plan{}, err
	}
	defer closeConfig()
	obj, err := k.read(ctx, ref)
	if err != nil {
		return Plan{}, err
	}
	if !obj.matches(ref) || obj.metadata()["deletionTimestamp"] != nil {
		return Plan{}, errors.New(locales.KubeResourceChanged())
	}
	draft := KubeDraft{Ref: ref, Version: obj.version(), config: hash}

	suffix := "-manual-" + strings.ToLower(rand.Text())
	name := strings.TrimRight(ref.Name[:min(len(ref.Name), 63-len(suffix))], ".-") + suffix
	data, err := k.run(ctx, nil, "create", "job", name, "--from=cronjob/"+ref.Name,
		"--namespace="+ref.Namespace, "--dry-run=client", "-o", "json")
	if err != nil {
		return Plan{}, err
	}
	job, err := decodeResource(data)
	if err != nil || !cronRunMatches(job, ref, name) {
		return Plan{}, errors.New(locales.KubeResourceUnverified())
	}
	if _, err := draft.current(ctx, k); err != nil {
		return Plan{}, err
	}
	change := &KubeChange{draft: draft, jobName: name, input: job.manifest()}
	data, err = k.run(ctx, change.input, append(change.command(), "--dry-run=server")...)
	if err != nil {
		return Plan{}, err
	}
	preview, err := decodeResource(data)
	if err != nil || !cronRunMatches(preview, ref, name) {
		return Plan{}, errors.New(locales.KubeResourceUnverified())
	}
	if resourceSpec(preview)["suspend"] == true {
		return Plan{}, errors.New(locales.KubeCronRunSuspended())
	}
	return Plan{
		Title: locales.KubeCronRunTitle(ref.Name), Why: locales.KubeCronRunPreview(name), Action: locales.KubeCronRunAction(),
		Env: slices.Clone(env), Steps: []Step{{Kube: change, Argv: append([]string{ref.Kubectl, "--context=" + ref.Context}, change.command()...)}},
	}, nil
}

func cronRunMatches(job resourceJSON, source KubeResource, name string) bool {
	meta := job.metadata()
	if job["apiVersion"] != "batch/v1" || job["kind"] != "Job" ||
		meta["name"] != name || meta["namespace"] != source.Namespace || meta["deletionTimestamp"] != nil {
		return false
	}
	owners, _ := meta["ownerReferences"].([]any)
	return slices.ContainsFunc(owners, func(value any) bool {
		owner, _ := value.(map[string]any)
		return owner["controller"] == true && owner["apiVersion"] == "batch/v1" &&
			owner["kind"] == "CronJob" && owner["name"] == source.Name && owner["uid"] == source.UID
	})
}

func (m *KubeChange) startCronJob(ctx context.Context, k resourceClient, checking func()) (string, error) {
	source := m.draft.Ref
	name := m.jobName
	ref := source
	ref.Kind, ref.Name, ref.UID = "Job", name, ""
	data, err := k.run(ctx, m.input, m.command()...)
	if err != nil {
		return "", fmt.Errorf("%s: %w", locales.KubeCronRunUnverified(name), k.checkUnacknowledgedCreate(ctx, ref, err, checking))
	}
	created, err := decodeResource(data)
	uid, _ := created.metadata()["uid"].(string)
	if err != nil || uid == "" || !cronRunMatches(created, source, name) {
		cause := errors.New(locales.KubeCronRunUnverified(name))
		return "", k.checkUnacknowledgedCreate(ctx, ref, cause, checking)
	}
	checking()
	ref.UID = uid

	check, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()
	ticker := time.NewTicker(500 * time.Millisecond)
	defer ticker.Stop()
	for {
		job, err := k.read(check, ref)
		if err != nil {
			return "", fmt.Errorf("%s: %w", locales.KubeCronRunPending(name), err)
		}
		if !job.matches(ref) || !cronRunMatches(job, source, name) {
			return "", errors.New(locales.KubeCronRunPending(name))
		}
		status, _ := job["status"].(map[string]any)
		if started, _ := status["startTime"].(string); started != "" {
			return locales.KubeCronRunStarted(name), nil
		}
		select {
		case <-check.Done():
			return "", errors.New(locales.KubeCronRunPending(name))
		case <-ticker.C:
		}
	}
}
